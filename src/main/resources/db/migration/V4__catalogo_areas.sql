-- ========================================================
-- V4: Catálogo de áreas (3FN)
-- ========================================================
-- USUARIOS.AREA era texto libre: el mismo área podía quedar escrita de varias
-- formas ("operaciones", "Operaciones "). Pasa a un catálogo AREAS y USUARIOS
-- la referencia por ID_AREA. Los valores ya escritos se conservan.

-- Oracle Autonomous ejecuta DML en paralelo por defecto; en esa modalidad la
-- transacción no puede volver a leer AREAS después de insertar (ORA-12839).
ALTER SESSION DISABLE PARALLEL DML;

CREATE TABLE AREAS (
    ID             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE         VARCHAR2(80) NOT NULL,
    ESTADO         VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_AREAS PRIMARY KEY (ID),
    CONSTRAINT UK_AREAS_NOMBRE UNIQUE (NOMBRE),
    CONSTRAINT CK_AREAS_ESTADO CHECK (ESTADO IN ('ACTIVO', 'INACTIVO'))
);

-- Áreas habituales de una empresa de mantención eléctrica en terreno.
INSERT INTO AREAS (NOMBRE)
SELECT 'Administración' FROM DUAL
UNION ALL SELECT 'Comercial' FROM DUAL
UNION ALL SELECT 'Finanzas' FROM DUAL
UNION ALL SELECT 'Gerencia' FROM DUAL
UNION ALL SELECT 'Operaciones' FROM DUAL
UNION ALL SELECT 'Soporte técnico' FROM DUAL
UNION ALL SELECT 'Terreno' FROM DUAL;

-- Áreas ya escritas en USUARIOS que no están en la lista base (sin distinguir
-- mayúsculas ni espacios), con la primera letra en mayúscula.
INSERT INTO AREAS (NOMBRE)
SELECT DISTINCT UPPER(SUBSTR(a.NOMBRE_LIMPIO, 1, 1)) || SUBSTR(a.NOMBRE_LIMPIO, 2)
FROM (
    SELECT TRIM(REGEXP_REPLACE(AREA, '\s+', ' ')) AS NOMBRE_LIMPIO
    FROM USUARIOS
    WHERE AREA IS NOT NULL AND TRIM(AREA) IS NOT NULL
) a
WHERE NOT EXISTS (
    SELECT 1 FROM AREAS x WHERE LOWER(x.NOMBRE) = LOWER(a.NOMBRE_LIMPIO)
);

ALTER TABLE USUARIOS ADD (ID_AREA NUMBER(19));

UPDATE USUARIOS u
SET u.ID_AREA = (
    SELECT x.ID FROM AREAS x
    WHERE LOWER(x.NOMBRE) = LOWER(TRIM(REGEXP_REPLACE(u.AREA, '\s+', ' ')))
)
WHERE u.AREA IS NOT NULL;

ALTER TABLE USUARIOS ADD CONSTRAINT FK_USUARIOS_AREA FOREIGN KEY (ID_AREA) REFERENCES AREAS (ID);
CREATE INDEX IDX_USUARIOS_AREA ON USUARIOS (ID_AREA);

ALTER TABLE USUARIOS DROP COLUMN AREA;
